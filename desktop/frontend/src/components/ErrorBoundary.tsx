// Last-resort render guard. When a component throws during render, React 18
// unmounts the whole tree — the window would go blank. This boundary swaps
// the crash for a panel with the error and a reload button.
//
// It deliberately sits ABOVE the I18nProvider (a broken provider is exactly
// the kind of crash it must survive), so the fallback cannot call useT.
// It renders through the pure translate() core instead, resolving the
// language itself; every bridge call is guarded because outside a live Wails
// window the binding throws synchronously — and that failure must not take
// down the crash screen too.
import { Component, type ReactNode } from "react";
import { catalogues, FALLBACK, translate } from "../lib/i18n";
// @ts-ignore wailsjs bindings are generated by wails build
import { GetLanguage } from "../../wailsjs/go/controllers/System";

type Props = { children: ReactNode };
type State = { error: Error | null; lang: string };

export default class ErrorBoundary extends Component<Props, State> {
  state: State = { error: null, lang: FALLBACK };

  componentDidMount() {
    try {
      GetLanguage()
        .then((code: string) => code && this.setState({ lang: code }))
        .catch(() => {
          /* keep the fallback language */
        });
    } catch {
      /* no Wails runtime attached (tests, early crash): stay on the fallback */
    }
  }

  static getDerivedStateFromError(error: Error): Partial<State> {
    return { error };
  }

  render() {
    const { error, lang } = this.state;
    if (error === null) return this.props.children;
    const t = (key: string) => translate(catalogues, lang, key);
    return (
      <div className="flex h-screen w-screen items-center justify-center p-8">
        <div className="glass-strong w-full max-w-[640px] p-6">
          <h1 className="mb-1 text-lg font-semibold text-white">{t("errorBoundary.title")}</h1>
          <p className="mb-4 text-xs text-white/60">{t("errorBoundary.description")}</p>
          <pre className="mb-4 max-h-60 overflow-auto whitespace-pre-wrap rounded-lg bg-black/30 p-3 text-[11px] text-red-300/90">
            {error.message}
            {error.stack ? "\n\n" + error.stack : ""}
          </pre>
          <button
            type="button"
            onClick={() => window.location.reload()}
            className="rounded-lg border border-accent bg-accent/30 px-4 py-1.5 text-sm text-white transition-colors hover:bg-accent/40"
          >
            {t("errorBoundary.reload")}
          </button>
        </div>
      </div>
    );
  }
}
